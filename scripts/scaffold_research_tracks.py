def slug(text: str) -> str:
    return re.sub(r"(^-|-$)", "", re.sub(r"[^a-z0-9]+", "-", text.lower()))


def readme(group: str, module_id: str, title: str, summary: str, program: str) -> str:
    return f"""# {module_id} — {title}

**Program:** `{program}`  
**Track:** {group}  
**Module:** {module_id}  
**Status:** Scaffold / not yet researched

## Простими словами

{summary}

## Початкове дослідницьке питання

> За яких умов цей механізм або проблема реально змінює безпеку, реконструкцію інформації, корисність чи вартість системи?

## Межі модуля

Це картка-навігатор, а не готовий висновок. До експерименту запиши припущення, виключення, залежності та критерії зупинки.

## Наступний крок

1. Додай конкретний приклад.
2. Сформулюй вузьку та нульову гіпотези.
3. Запиши критерії фальсифікації.
4. Спроєктуй експеримент і лише потім код.
"""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    created = skipped = 0
    for group, data in TRACKS.items():
        base = args.root / "research" / data["program"] / "tracks"
        for module_id, title, summary in data["items"]:
            target = base / f"{module_id}-{slug(title)}" / "README.md"
            if target.exists() and not args.force:
                print(f"SKIP   {target}")
                skipped += 1
                continue
            print(f"CREATE {target}")
            if not args.dry_run:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(
                    readme(group, module_id, title, summary, data["program"]),
                    encoding="utf-8",
                )
            created += 1
    print(f"Done: {created} created, {skipped} skipped, {created + skipped} total")


if __name__ == "__main__":
    main()
